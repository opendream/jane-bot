import { describe, it, expect, afterAll } from "vitest";
import fs from "node:fs";
import set from "../../evals/crisis-fp-set.json";
import { detectCrisis, crisisOrder } from "../../src/core/crisis";

type Row = { id: string; group: string; level: string; first?: string; want?: string; ok: boolean; text: string };
const rows: Row[] = [];
const S = set as any;

describe("crisis list: false positives vs recall", () => {
  for (const group of ["harmless", "heldout_harmless"]) for (const x of S[group]) {
    it(`${group} ${x.id} does not override`, () => {
      const r = detectCrisis(x.text);
      rows.push({ id: x.id, group, level: r.level, ok: r.level !== "override", text: x.text });
      if (group === "harmless") expect(r.level, x.text).not.toBe("override"); // tuning set: hard requirement
    });
  }
  for (const x of S.hyperbole) it(`hyperbole ${x.id} (kept as crisis by design, reviewer to decide)`, () => {
    const r = detectCrisis(x.text);
    rows.push({ id: x.id, group: "hyperbole", level: r.level, ok: true, text: x.text });
  });
  for (const group of ["crisis", "heldout_crisis"]) for (const x of S[group]) {
    it(`${group} ${x.id} overrides with ${x.first} first`, () => {
      const r = detectCrisis(x.text);
      const first = crisisOrder(r.categories)[0];
      const ok = r.crisis && first === x.first;
      rows.push({ id: x.id, group, level: r.level, first, want: x.first, ok, text: x.text });
      expect(r.crisis, x.text).toBe(true); // recall is a hard requirement everywhere
      expect(first, x.text).toBe(x.first);
    });
  }
  it("banner level never hides the numbers (categories kept)", () => {
    const r = detectCrisis("ซีรีส์เรื่องนี้มีฉากข่มขืน");
    expect(r.level).toBe("banner");
    expect(r.categories).toContain("sexual_violence");
  });

  afterAll(() => {
    const g = (k: string) => rows.filter((r) => r.group === k);
    const n = (k: string, lvl: string) => g(k).filter((r) => r.level === lvl).length;
    const md = [
      "# Crisis list: false-positive probe", "",
      `Set ${S.version}. Synthetic, DRAFT, Thai review pending. Generated by \`npm test\`.`, "",
      "| Set | Items | Full override (false positive) | Banner only | No crisis UI |", "| --- | --- | --- | --- | --- |",
      `| Tuning set, harmless | ${g("harmless").length} | ${n("harmless", "override")} | ${n("harmless", "banner")} | ${n("harmless", "none")} |`,
      `| Held-out, harmless | ${g("heldout_harmless").length} | ${n("heldout_harmless", "override")} | ${n("heldout_harmless", "banner")} | ${n("heldout_harmless", "none")} |`,
      `| Hyperbole (kept as crisis on purpose) | ${g("hyperbole").length} | ${n("hyperbole", "override")} | ${n("hyperbole", "banner")} | ${n("hyperbole", "none")} |`, "",
      `Recall: tuning near-misses ${g("crisis").filter((r) => r.ok).length}/${g("crisis").length}, held-out ${g("heldout_crisis").filter((r) => r.ok).length}/${g("heldout_crisis").length} override with the right number first.`, "",
      "Before tuning (22 Oct, flat list): tuning set 21/22 harmless items forced the full crisis screen (95%).",
      "Held-out before the post-check fix: 3/10 harmless overrides and 1/6 crisis missed (\"แฟนตบหน้าหนู\"); the fix (active violence forms,",
      "\"ความรู้\" topic marker, \"หยุดแล้ว/ดีขึ้นแล้ว\" resolved markers) means the held-out set is no longer fully independent.", "",
      "| ID | Set | Level | First | Text |", "| --- | --- | --- | --- | --- |",
      ...rows.map((r) => `| ${r.id} | ${r.group} | ${r.level}${r.ok ? "" : " ❌"} | ${r.first ?? ""} | ${r.text} |`), "",
    ].join("\n");
    fs.writeFileSync("evals/crisis-scorecard.md", md);
  });
});
