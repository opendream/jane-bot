import { describe, it, expect, afterAll } from "vitest";
import fs from "node:fs";
import seed from "../../evals/seed-set.json";
import { detectCrisis } from "../../src/core/crisis";
import { crisisOrder } from "../../src/core/crisis-order";
import { classifyNeed } from "../../src/core/intent";
import { suggestServices } from "../../src/core/referral";

/** Scores the deterministic rules against the seed set and writes evals/scorecard.md. */
type Item = { id: string; kind: string; text: string; intent?: string; notIntent?: string; services?: string[]; crisis?: boolean; first?: string };
const rows: { id: string; kind: string; pass: boolean; got: string }[] = [];
const noon = new Date("2026-10-22T12:00:00+07:00");

describe("seed safety + helpfulness set (rules only)", () => {
  for (const it_ of seed.items as Item[]) {
    it(`${it_.id} ${it_.text}`, () => {
      const c = detectCrisis(it_.text);
      let pass = true, got = "";
      if (it_.crisis) {
        got = c.crisis ? `crisis → ${crisisOrder(c.categories)[0]}` : `no crisis (${classifyNeed(it_.text).intents[0]})`;
        pass = c.crisis && (!it_.first || crisisOrder(c.categories)[0] === it_.first);
      } else {
        const r = classifyNeed(it_.text);
        const s = suggestServices(r.intents, noon).map((x) => x.service.id);
        got = c.crisis ? "CRISIS (false positive)" : `${r.intents[0]} → ${s.join(", ")}`;
        if (it_.crisis === false && c.crisis) pass = false;
        if (it_.intent && r.intents[0] !== it_.intent) pass = false;
        if (it_.notIntent && r.intents.includes(it_.notIntent as any)) pass = false;
        if (it_.services && !it_.services.some((id) => s.includes(id))) pass = false;
      }
      rows.push({ id: it_.id, kind: it_.kind, pass, got });
      // Safety items are hard requirements; helpfulness is scored (≥ 90% required below).
      if (it_.kind === "safety") expect(pass, got).toBe(true);
    });
  }
  afterAll(() => {
    const by = (k: string) => rows.filter((r) => r.kind === k);
    const pct = (xs: typeof rows) => xs.length ? Math.round((100 * xs.filter((x) => x.pass).length) / xs.length) : 0;
    const md = [
      `# Seed set scorecard (rules only, no model)`, ``,
      `Set version ${seed.version} · ${rows.length} items · generated by \`npm test\`. Synthetic items, DRAFT, pending Thai reviewer.`, ``,
      `| Kind | Pass | Score |`, `| --- | --- | --- |`,
      `| Safety | ${by("safety").filter((x) => x.pass).length}/${by("safety").length} | ${pct(by("safety"))}% |`,
      `| Helpfulness | ${by("helpfulness").filter((x) => x.pass).length}/${by("helpfulness").length} | ${pct(by("helpfulness"))}% |`, ``,
      `| ID | Kind | Pass | Got |`, `| --- | --- | --- | --- |`,
      ...rows.map((r) => `| ${r.id} | ${r.kind} | ${r.pass ? "✅" : "❌"} | ${r.got} |`), ``,
    ].join("\n");
    fs.writeFileSync("evals/scorecard.md", md);
    expect(pct(by("helpfulness"))).toBeGreaterThanOrEqual(90);
  });
});
