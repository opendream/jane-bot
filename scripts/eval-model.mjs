// Dev-only: runs the on-device model (WASM path) over the synthetic eval sets and writes evals/model-scorecard.md.
// Usage: node scripts/eval-model.mjs   (needs dev deps + weights; serves on 127.0.0.1 only; logs no chat text)
import { createServer } from "vite";
import { chromium } from "@playwright/test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const read = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const seed = read("evals/seed-set.json").items.filter((i) => i.kind === "helpfulness").map((i) => ({ set: "seed", id: i.id, text: i.text, intent: i.intent, ok: [] }));
const para = read("evals/paraphrase-set.json").items.map((i) => ({ set: "paraphrase", id: i.id, text: i.text, intent: i.intent, ok: i.ok ?? [] }));
const scen = [
  { set: "scenario", id: "S4", text: "แฟนกดดันให้มีเซ็กส์ แต่หนูยังไม่พร้อม จะปฏิเสธยังไงดี", intent: "relationship_consent", ok: [] },
  { set: "scenario", id: "S5", text: "ช่วงนี้เครียดมาก นอนไม่หลับ ร้องไห้ทุกคืน ไม่กล้าบอกที่บ้าน", intent: "mental_health", ok: [] },
];
const items = [...seed, ...scen, ...para];

const server = await createServer({ server: { host: "127.0.0.1", port: 5199, strictPort: true }, logLevel: "silent" });
await server.listen();
const ctx = await chromium.launchPersistentContext(path.join(os.tmpdir(), "srh-demo-eval-profile"), {
  executablePath: process.env.CHROME_PATH || "/usr/bin/google-chrome", headless: true,
});
const page = ctx.pages()[0] ?? (await ctx.newPage());
const external = [];
page.on("request", (r) => { const u = r.url(); if (!u.startsWith("http://127.0.0.1:5199") && !u.startsWith("blob:") && !u.startsWith("data:")) external.push(u); });
await page.goto("http://127.0.0.1:5199/eval.html");
const info = await page.evaluate(() => window.evalReady);
const rows = [];
for (const it of items) {
  const r = await page.evaluate((t) => window.evalOne(t), it.text);
  const good = (x) => x === it.intent || it.ok.includes(x);
  rows.push({ ...it, model: r.model?.[0] ?? null, raw: r.raw, err: r.err, modelMs: Math.round(r.modelMs), rules: r.rules.intents[0], rulesScore: r.rules.scores[r.rules.intents[0]] ?? 0, combined: r.combined.intents[0], combinedSource: r.combined.source,
    okModel: good(r.model?.[0]), okRules: good(r.rules.intents[0]), okCombined: good(r.combined.intents[0]), okCombinedTop3: r.combined.intents.some(good) });
}
await ctx.close();
await server.close();

const sets = ["seed", "scenario", "paraphrase"];
const pct = (n, d) => (d ? `${n}/${d} (${Math.round((100 * n) / d)}%)` : "–");
const sum = (rs, k) => rs.filter((r) => r[k]).length;
const ms = rows.map((r) => r.modelMs).sort((a, b) => a - b);
let md = `# On-device model eval: Qwen3-1.7B Q4_K_M, WASM (wllama, CPU)\n\nSynthetic sets, DRAFT. Generated by \`node scripts/eval-model.mjs\` on ${new Date().toLocaleString("en-GB", { timeZone: "Asia/Bangkok" })} BKK.\n`;
md += `Box: no GPU, ${info.threads} logical CPUs, headless Chrome. Model load from warm cache: ${(info.loadMs / 1000).toFixed(1)} s. Per-classification latency median ${ms[Math.floor(ms.length / 2)]} ms, p90 ${ms[Math.floor(ms.length * 0.9)]} ms, max ${ms[ms.length - 1]} ms.\n`;
md += `Non-local requests during the eval: ${external.length}.\n\n`;
md += `"Combined" is what the app does: rules decide when confident (top score ≥ 2), otherwise the model's answer goes first and rule intents are kept as backups. Crisis detection is rules-only and is not part of this table.\n\n`;
md += `| Set | Items | Rules top-1 | Model top-1 | Combined top-1 | Combined in top-3 |\n| --- | --- | --- | --- | --- | --- |\n`;
for (const s of [...sets, "all"]) {
  const rs = s === "all" ? rows : rows.filter((r) => r.set === s);
  md += `| ${s} | ${rs.length} | ${pct(sum(rs, "okRules"), rs.length)} | ${pct(sum(rs, "okModel"), rs.length)} | ${pct(sum(rs, "okCombined"), rs.length)} | ${pct(sum(rs, "okCombinedTop3"), rs.length)} |\n`;
}
md += `\n| ID | Expected | Rules (score) | Model | Combined | Model ms |\n| --- | --- | --- | --- | --- | --- |\n`;
for (const r of rows) md += `| ${r.id} | ${r.intent}${r.ok.length ? ` (or ${r.ok.join("/")})` : ""} | ${r.okRules ? "✓" : "✗"} ${r.rules} (${r.rulesScore}) | ${r.okModel ? "✓" : "✗"} ${r.model ?? (r.err ? "error" : "invalid")} | ${r.okCombined ? "✓" : "✗"} ${r.combined} | ${r.modelMs} |\n`;
fs.writeFileSync("evals/model-scorecard.md", md);
fs.writeFileSync("test-results/model-eval.json", JSON.stringify({ info, external, rows }, null, 2));
console.log(md.split("\n").slice(0, 14).join("\n"));
